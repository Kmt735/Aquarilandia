test('resposta perdida na entrada reutiliza chave após reload, sem somar unidades duas vezes',async({page,contas,sistema})=>{
  await entrar(page,contas);const p=await cadastrar(page,sistema,{nome:'AAA Demo Repetição',preco:'10,00',peixe:false})
  await page.getByRole('button',{name:`Dar entrada no estoque: ${p.nome}`}).click()
  await page.locator('#entrada-quantidade').fill('3');await page.locator('#entrada-motivo').fill('Conferência de nova tentativa')
  let chave
  await page.route('**/api/estoque/movimentacoes',async r=>{chave=r.request().headers()['idempotency-key'];await r.fetch();await r.abort()},{times:1})
  await page.getByRole('button',{name:'Registrar entrada',exact:true}).click()
  await expect(page.getByText('Não foi possível conectar ao servidor. Tente novamente.',{exact:true})).toBeVisible()
  await page.reload();await page.getByRole('button',{name:`Dar entrada no estoque: ${p.nome}`}).click()
  await expect(page.locator('#entrada-quantidade')).toBeDisabled()
  const resposta=page.waitForResponse(r=>r.url().endsWith('/api/estoque/movimentacoes')&&r.request().method()==='POST')
  await page.getByRole('button',{name:'Confirmar a mesma entrada'}).click()
  const r=await resposta;expect(r.request().headers()['idempotency-key']).toBe(chave);expect(r.status()).toBe(201)
  await expect(page.getByText('Entrada registrada: 3 unidades. Saldo após a operação: 3.',{exact:true})).toBeVisible()
  expect((await sistema.cliente.query('SELECT estoque FROM produtos WHERE id=$1',[p.id])).rows[0].estoque).toBe(3)
  expect((await sistema.cliente.query("SELECT count(*)::int n FROM movimentacoes_estoque WHERE produto_id=$1 AND tipo='entrada'",[p.id])).rows[0].n).toBe(1)
})
