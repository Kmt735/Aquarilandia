async function cadastrar(page,sistema,{nome,preco,peixe=true}) {
  const categoria = (await sistema.cliente.query('SELECT id FROM categorias WHERE slug=$1',[peixe?'peixes':'acessorios'])).rows[0].id
  await page.goto('/admin/produtos/novo')
  await page.locator('#item-categoria').selectOption(String(categoria))
  await page.locator('#item-nome').fill(nome);await page.locator('#item-preco').fill(preco)
  if(peixe){
    for (const [campo,valor] of Object.entries({nomeCientifico:`Species ${nome}`,tamanhoAdultoCm:'5',aquarioMinLitros:'40',tempMinC:'24',tempMaxC:'28',phMin:'6',phMax:'7'})) await page.locator(`[name="peixes__${campo}"]`).fill(valor)
    for (const [campo,valor] of Object.entries({tipoAgua:'doce',temperamento:'pacifico',dificuldade:'iniciante'})) await page.locator(`[name="peixes__${campo}"]`).selectOption(valor)
  }
  const resposta=page.waitForResponse(r=>r.url().endsWith('/api/produtos')&&r.request().method()==='POST')
  await page.getByRole('button',{name:'Cadastrar item',exact:true}).click()
  const r=await resposta;expect(r.status()).toBe(201)
  const produto=await r.json();expect(produto.emEstoque).toBe(false)
  await expect(page.getByText(nome,{exact:true})).toBeVisible()
  return produto
}
async function abastecer(page,nome,qtd=7){
  await page.getByRole('button',{name:`Dar entrada no estoque: ${nome}`,exact:true}).click()
  await expect(page.getByRole('dialog').getByText('Saldo atual:',{exact:false})).toBeVisible()
  await page.locator('#entrada-quantidade').fill(String(qtd));await page.locator('#entrada-motivo').fill('Entrada fictícia conferida para demonstração')
  await page.getByRole('button',{name:'Registrar entrada',exact:true}).click()
  await expect(page.getByText(`Entrada registrada: ${qtd} unidades. Saldo após a operação: ${qtd}.`,{exact:true})).toBeVisible()
  await expect(page.getByRole('dialog').getByText(`Saldo atual: ${qtd} unidades.`,{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Concluir',exact:true}).click()
}
